export type Key = keyof typeof dict.ru
export const t = (lang: Lang, k: Key): string => dict[lang][k] ?? dict.ru[k]

export function plural(lang: Lang, n: number, forms: [string, string, string]): string {
  if (lang === 'en') return n === 1 ? forms[0] : forms[1]
  const m10 = n % 10, m100 = n % 100
  if (m10 === 1 && m100 !== 11) return forms[0]
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1]
  return forms[2]
}
export const sessionsWord = (lang: Lang, n: number) => plural(lang, n, lang === 'ru' ? ['сессия', 'сессии', 'сессий'] : ['session', 'sessions', 'sessions'])
